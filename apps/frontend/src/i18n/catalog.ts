const escapeRegex = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const frToEn = new Map<string, string>();
const enToFr = new Map<string, string>();

[...pairs, ...phrasePairs].forEach(([fr, en]) => {
  frToEn.set(fr, en);
  enToFr.set(en, fr);
});

const buildRegexTranslations = (source: Pair[], direction: "fr-en" | "en-fr", wholeWord = false): RegexTranslation[] => {
  return source
    .slice()
    .sort((a, b) => b[0].length - a[0].length)
    .map(([fr, en]) => {
      const from = direction === "fr-en" ? fr : en;
      const to = direction === "fr-en" ? en : fr;
      const body = escapeRegex(from);
      const pattern = wholeWord ? new RegExp(`\\b${body}\\b`, "gi") : new RegExp(body, "g");
      return [pattern, to] as const;
    });
};

export const phraseTranslations = buildRegexTranslations(phrasePairs, "fr-en");
export const reversePhraseTranslations = buildRegexTranslations(phrasePairs, "en-fr");
export const wordTranslations = buildRegexTranslations(wordPairs, "fr-en", true);
export const reverseWordTranslations = buildRegexTranslations(wordPairs, "en-fr", true);

const preserveCase = (source: string, translated: string) => {
  if (!source) return translated;
  if (source === source.toUpperCase()) return translated.toUpperCase();
  if (source[0] === source[0].toUpperCase()) return translated.charAt(0).toUpperCase() + translated.slice(1);
  return translated;
};

const applyRegexTranslations = (value: string, translations: RegexTranslation[]) => {
  let translated = value;
  translations.forEach(([pattern, replacement]) => {
    translated = translated.replace(pattern, (match) => preserveCase(match, replacement));
  });
  return translated;
};

export const translateValue = (value: string, language: AppLanguage) => {
  const trimmed = value.trim();
  if (!trimmed) return value;

  const direct = language === "en" ? frToEn.get(trimmed) : enToFr.get(trimmed);
  if (direct) return value.replace(trimmed, direct);

  const phraseSet = language === "en" ? phraseTranslations : reversePhraseTranslations;
  const wordSet = language === "en" ? wordTranslations : reverseWordTranslations;
  return applyRegexTranslations(applyRegexTranslations(value, phraseSet), wordSet);
};

export const getStoredLanguage = (): AppLanguage => {
  if (typeof window === "undefined") return "fr";
  return localStorage.getItem(languageStorageKey) === "en" ? "en" : "fr";
};

export const setStoredLanguage = (language: AppLanguage) => {
  if (typeof window === "undefined") return;
  localStorage.setItem(languageStorageKey, language);
  window.dispatchEvent(new CustomEvent(languageChangeEvent, { detail: language }));
};
